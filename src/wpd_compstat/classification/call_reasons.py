def match_key(call_type: str | None) -> str:
    return " ".join((call_type or "").casefold().split())


# Call types in the CAD exports that are keying slips of one official reason.
# CVSCHECK CONDITION is left out until Joel says what the prefix means.
VARIANTS: dict[str, str] = {
    "FRAUD IN PROGESS": "FRAP",
    "FOLLOW-UP INVESTIGATIONQ": "FU",
    "`Assist DEA": "ASDE",
    "'Assist DEA": "ASDE",
    "AUTO THEFT`": "AUT",
    "AUTO THEFT'": "AUT",
    "AASSIST CITIZEN": "ASSC",
    "DISABLED MV`": "DMV",
    "DISABLED MV'": "DMV",
    "CHECK CONDITIONQ": "CHKC",
    "CHECK CONDITION+": "CHKC",
}

_BY_KEY = {match_key(description): code for code, description in CALL_REASONS}
_BY_KEY.update({match_key(variant): code for variant, code in VARIANTS.items()})


def official_code(call_type: str | None) -> str | None:
    """The IMC code whose description is this call type, ignoring case and spacing."""
    return _BY_KEY.get(match_key(call_type))


def seed_call_reasons(conn, stamp: str) -> None:
    for code, description in CALL_REASONS:
        conn.execute(
            """
            INSERT INTO call_reasons(code, description, match_key, source, updated_at)
            VALUES (?, ?, ?, ?, ?)
            ON CONFLICT(code) DO UPDATE SET
                description = excluded.description,
                match_key = excluded.match_key,
                source = excluded.source,
                updated_at = excluded.updated_at
            WHERE call_reasons.description != excluded.description OR call_reasons.source != excluded.source
            """,
            (code, description, match_key(description), SOURCE, stamp),
        )
